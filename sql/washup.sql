-- WASHUP: skema PostgreSQL (konversi dari MySQL/MariaDB).
-- Buat database washup terlebih dahulu, lalu jalankan: psql -U postgres -d washup -f sql/washup.sql
-- Soft delete digunakan pada tabel operasional/master yang memiliki deleted_at.
-- Tabel penghubung dan riwayat publikasi menggunakan aturan penghapusan tersendiri.
-- ENUM MySQL diganti VARCHAR + CHECK (lebih mudah dipakai dengan PDO).
-- Kolom generated "*_aktif" diganti partial unique index (UNIQUE ... WHERE deleted_at IS NULL).

CREATE TABLE karyawan (
  id_karyawan     INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nama_karyawan   VARCHAR(100) NOT NULL,
  no_telepon      VARCHAR(20),
  alamat          VARCHAR(255),
  role            VARCHAR(20) NOT NULL CHECK (role IN ('Admin','Kasir','Petugas','Owner')),
  status_karyawan VARCHAR(100) NOT NULL DEFAULT 'Aktif',
  gaji_harian     INT NOT NULL DEFAULT 0,
  username        VARCHAR(100) NOT NULL,
  password        VARCHAR(255) NOT NULL,   -- hash password_hash(), bukan teks asli
  status_akun      VARCHAR(20) NOT NULL DEFAULT 'Aktif' CHECK (status_akun IN ('Aktif','Nonaktif')),
  is_system_account BOOLEAN NOT NULL DEFAULT FALSE,
  deleted_at        TIMESTAMP NULL,
  CONSTRAINT chk_system_account_role CHECK (NOT is_system_account OR role = 'Admin')
);
-- Username dapat dipakai kembali setelah akun lama di-soft-delete.
CREATE UNIQUE INDEX uq_username_aktif ON karyawan (username) WHERE deleted_at IS NULL;
-- Maksimal satu akun sistem aktif; akun ini adalah Admin utama yang dibuat oleh seed.php.
CREATE UNIQUE INDEX uq_system_account ON karyawan (is_system_account)
  WHERE is_system_account = TRUE AND deleted_at IS NULL;

CREATE TABLE pelanggan (
  id_pelanggan   INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nama_pelanggan VARCHAR(100) NOT NULL,
  no_telepon     VARCHAR(20),
  deleted_at     TIMESTAMP NULL
);

-- Satu baris antrean = satu nomor antrean.
CREATE TABLE antrean (
  id_antrean                INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  tanggal_antrean           DATE NOT NULL DEFAULT CURRENT_DATE,
  nomor_antrean             INT NOT NULL,
  waktu_masuk               TIME NOT NULL DEFAULT LOCALTIME(0),
  status_antrean            VARCHAR(20) NOT NULL DEFAULT 'Menunggu'
                              CHECK (status_antrean IN ('Menunggu','Sedang Dicuci','Selesai')),
  waktu_mulai               TIME NULL,
  waktu_selesai             TIME NULL,
  waktu_perubahan_terakhir  TIMESTAMP NULL DEFAULT CURRENT_TIMESTAMP,
  deleted_at                TIMESTAMP NULL
);
CREATE UNIQUE INDEX uq_nomor_per_hari ON antrean (tanggal_antrean, nomor_antrean) WHERE deleted_at IS NULL;

-- Pengganti ON UPDATE CURRENT_TIMESTAMP
CREATE OR REPLACE FUNCTION set_waktu_perubahan() RETURNS trigger AS $$
BEGIN
  NEW.waktu_perubahan_terakhir = NOW();
  RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER trg_antrean_ubah BEFORE UPDATE ON antrean
  FOR EACH ROW EXECUTE FUNCTION set_waktu_perubahan();

CREATE TABLE kendaraan (
  id_kendaraan    INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_pelanggan    INT NOT NULL REFERENCES pelanggan(id_pelanggan),
  id_antrean      INT NULL REFERENCES antrean(id_antrean),
  nomor_plat      VARCHAR(20) NOT NULL,
  jenis_kendaraan VARCHAR(100) NOT NULL,
  merk_kendaraan  VARCHAR(100) NULL,
  tipe_kendaraan  VARCHAR(100) NULL,
  deleted_at      TIMESTAMP NULL
);
CREATE INDEX idx_plat ON kendaraan (nomor_plat);

CREATE TABLE layanan (
  id_layanan      INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nama_layanan    VARCHAR(100) NOT NULL,
  jenis_kendaraan VARCHAR(100) NOT NULL,
  harga           INT NOT NULL,
  deskripsi       VARCHAR(255) NULL,
  status_layanan  VARCHAR(20) NOT NULL DEFAULT 'Aktif' CHECK (status_layanan IN ('Aktif','Nonaktif')),
  deleted_at      TIMESTAMP NULL
);

CREATE TABLE transaksi (
  id_transaksi       INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  no_transaksi       VARCHAR(30) NOT NULL,          -- contoh TRX-20261115-001
  id_kendaraan       INT NOT NULL REFERENCES kendaraan(id_kendaraan),
  id_antrean         INT NOT NULL REFERENCES antrean(id_antrean),
  id_karyawan        INT NOT NULL REFERENCES karyawan(id_karyawan),  -- kasir pembuat transaksi
  tanggal_transaksi  DATE NOT NULL,
  waktu_transaksi    TIME NOT NULL,
  total_harga        INT NOT NULL DEFAULT 0,
  diskon             INT NOT NULL DEFAULT 0,
  metode_pembayaran  VARCHAR(10) NULL CHECK (metode_pembayaran IN ('Tunai','QRIS')),
  status_pembayaran  VARCHAR(20) NOT NULL DEFAULT 'Belum Dibayar'
                       CHECK (status_pembayaran IN ('Belum Dibayar','Lunas')),
  uang_diterima      INT NULL,
  kembalian          INT NULL,
  waktu_pembayaran   TIMESTAMP NULL,
  deleted_at         TIMESTAMP NULL
);
CREATE UNIQUE INDEX uq_no_transaksi ON transaksi (no_transaksi) WHERE deleted_at IS NULL;

CREATE TABLE detail_transaksi (
  id_detail_transaksi INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_transaksi INT NOT NULL REFERENCES transaksi(id_transaksi),
  id_layanan   INT NOT NULL REFERENCES layanan(id_layanan),
  jumlah       INT NOT NULL DEFAULT 1,
  harga_satuan INT NOT NULL,
  subtotal     INT NOT NULL,
  deleted_at   TIMESTAMP NULL
);

CREATE TABLE antrean_karyawan (
  id_antrean  INT NOT NULL REFERENCES antrean(id_antrean),
  id_karyawan INT NOT NULL REFERENCES karyawan(id_karyawan),
  PRIMARY KEY (id_antrean, id_karyawan)
);

-- Master shift dan jadwal shift.
CREATE TABLE shift (
  id_shift     INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nama_shift   VARCHAR(100) NOT NULL,
  jam_mulai    TIME NOT NULL,
  jam_selesai  TIME NOT NULL,
  status_shift VARCHAR(20) NOT NULL DEFAULT 'Aktif' CHECK (status_shift IN ('Aktif','Nonaktif')),
  deleted_at   TIMESTAMP NULL
);

CREATE TABLE jadwal_shift (
  id_jadwal    INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_karyawan  INT NOT NULL REFERENCES karyawan(id_karyawan),
  tanggal      DATE NOT NULL,
  id_shift     INT NULL REFERENCES shift(id_shift),   -- NULL = libur
  deleted_at   TIMESTAMP NULL
);
CREATE UNIQUE INDEX uq_jadwal ON jadwal_shift (id_karyawan, tanggal) WHERE deleted_at IS NULL;

-- Salinan jadwal yang sudah "Tampilkan ke Owner".
CREATE TABLE jadwal_shift_terbit (
  id_jadwal    INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_karyawan  INT NOT NULL REFERENCES karyawan(id_karyawan),
  tanggal      DATE NOT NULL,
  id_shift     INT NULL REFERENCES shift(id_shift),
  deleted_at   TIMESTAMP NULL
);
CREATE UNIQUE INDEX uq_terbit ON jadwal_shift_terbit (id_karyawan, tanggal) WHERE deleted_at IS NULL;

CREATE TABLE jadwal_terbit_minggu (
  minggu_mulai  DATE PRIMARY KEY,           -- hari Senin
  waktu_terbit  TIMESTAMP NOT NULL
);

CREATE TABLE absensi (
  id_absensi        INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_karyawan       INT NOT NULL REFERENCES karyawan(id_karyawan),
  id_shift          INT NULL REFERENCES shift(id_shift),
  tanggal_absensi   DATE NOT NULL,
  jam_masuk         TIME NULL,
  jam_keluar        TIME NULL,
  status_absensi    VARCHAR(100) NOT NULL DEFAULT 'Hadir',
  keterangan        VARCHAR(255) NULL,
  foto_masuk        VARCHAR(255) NULL,      -- path file, bukan base64
  foto_keluar       VARCHAR(255) NULL,
  verifikasi_masuk  TIMESTAMP NULL,         -- diisi Admin saat verifikasi
  verifikasi_keluar TIMESTAMP NULL,
  deleted_at        TIMESTAMP NULL
);
-- satu absensi per karyawan per hari
CREATE UNIQUE INDEX uq_absensi_harian ON absensi (id_karyawan, tanggal_absensi) WHERE deleted_at IS NULL;

CREATE TABLE pengeluaran (
  id_pengeluaran      INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_karyawan         INT NOT NULL REFERENCES karyawan(id_karyawan),
  tanggal_pengeluaran DATE NOT NULL,
  keterangan          VARCHAR(255) NOT NULL,
  jumlah              INT NOT NULL DEFAULT 1,
  harga_satuan        INT NOT NULL,
  nominal_pengeluaran INT NOT NULL,         -- = jumlah x harga_satuan
  bukti_nota          VARCHAR(255) NULL,
  deleted_at          TIMESTAMP NULL
);

